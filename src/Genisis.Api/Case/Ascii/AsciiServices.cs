using Genisis.Api.Common;
using Genisis.Api.Data;

namespace Genisis.Api.Case.Ascii;

/// <summary>Case > Claim ASCII (legacy frmNewClaimAscii): builds the claim file of a payor, numbers the batch and flags what was exported.</summary>
public class ClaimAsciiService(IDbSessions sessions, IAsciiRepository repository, IAsciiFileStore files, ILogger<ClaimAsciiService> log)
{
    /// <summary>
    /// CmdGenerate_Click. The file is written inside the transaction, before the commit, so a failed write leaves nothing flagged.
    /// Throws <see cref="NotFoundException"/> ("No record found!") when there is nothing to export.
    /// </summary>
    public async Task<AsciiResult> GenerateAsync(ClaimAsciiRequest request, string userCode)
    {
        await using var session = await sessions.BeginAsync();
        var result = await GenerateAsync(session, request);
        await session.CommitAsync();
        log.LogInformation("Claim ASCII {File} ({Variant}) generated by {User}: {Records} record(s)", result.FileName, request.Rejected ? "rejected" : "accepted", userCode, result.Records);
        return result;
    }

    /// <summary>Generates inside the caller's unit of work (nothing is committed here).</summary>
    public async Task<AsciiResult> GenerateAsync(IDbSession session, ClaimAsciiRequest request)
    {
        var payor = AsciiPayor.Code(request.Payor);
        var from = request.DateFrom!.Value.Date;
        var to = request.DateTo!.Value.Date;
        var rows = request.Rejected
            ? await repository.GetRejectedClaimsAsync(session, payor, from, to)
            : await repository.GetAcceptedClaimsAsync(session, payor, from, to, request.ExportStatus!.Trim() == "R", request.WorksheetStatus!.Trim());
        if (rows.Count == 0) throw new NotFoundException("No record found!");

        var today = DateTime.Today;
        var batch = await repository.NextBatchAsync(session, "CLM", payor, today);
        var lines = new List<string> { AsciiFormat.ClaimHeader(request.Rejected ? payor : "MX", batch, today) };
        lines.AddRange(rows.Select(row => request.Rejected ? AsciiFormat.RejectedRecord(row) : AsciiFormat.AcceptedRecord(row)));
        lines.Add(AsciiFormat.ClaimTrailer(rows.Count));
        if (!request.Rejected)
            foreach (var row in rows)
                await repository.MarkClaimExportedAsync(session, row["CASNumber"]?.ToString()?.Trim() ?? "", Convert.ToInt32(row["ClaimVersion"]));

        return new(await files.WriteAsync(AsciiFileStore.ClaimKind, AsciiFormat.FileName(payor, today, batch), AsciiFormat.Join(lines)), rows.Count, batch);
    }

    /// <summary>The path of a generated claim file, or null.</summary>
    public string? FindFile(string name) => files.Find(AsciiFileStore.ClaimKind, name);
}

/// <summary>Case > Case ASCII (legacy frmCaseASCII): builds the case file of a payor, numbers the batch and flags what was exported.</summary>
public class CaseAsciiService(IDbSessions sessions, IAsciiRepository repository, IAsciiFileStore files, ILogger<CaseAsciiService> log)
{
    /// <summary>
    /// CmdGenerate_Click. The file is written inside the transaction, before the commit, so a failed write leaves nothing flagged.
    /// Throws <see cref="NotFoundException"/> ("No record found!") when there is nothing to export.
    /// </summary>
    public async Task<AsciiResult> GenerateAsync(CaseAsciiRequest request, string userCode)
    {
        await using var session = await sessions.BeginAsync();
        var result = await GenerateAsync(session, request);
        await session.CommitAsync();
        log.LogInformation("Case ASCII {File} generated by {User}: {Records} record(s)", result.FileName, userCode, result.Records);
        return result;
    }

    /// <summary>Generates inside the caller's unit of work (nothing is committed here).</summary>
    public async Task<AsciiResult> GenerateAsync(IDbSession session, CaseAsciiRequest request)
    {
        var payor = AsciiPayor.Code(request.Payor);
        var rows = await repository.GetCasesAsync(session, payor, request.DateFrom!.Value.Date, request.DateTo!.Value.Date,
            request.ExportStatus!.Trim() == "R", request.WorksheetStatus!.Trim());
        if (rows.Count == 0) throw new NotFoundException("No record found!");

        var today = DateTime.Today;
        var batch = await repository.NextBatchAsync(session, "CAS", payor, today);
        foreach (var row in rows) await repository.MarkCaseExportedAsync(session, row["CASNumber"]?.ToString()?.Trim() ?? "");

        var text = AsciiFormat.Join(rows.Select(row => AsciiFormat.CaseRecord(row, today, batch)));
        return new(await files.WriteAsync(AsciiFileStore.CaseKind, AsciiFormat.FileName(payor, today, batch), text), rows.Count, batch);
    }

    /// <summary>The path of a generated case file, or null.</summary>
    public string? FindFile(string name) => files.Find(AsciiFileStore.CaseKind, name);
}
