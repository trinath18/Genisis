# Regenerates the Tracking report case texts from the desktop's dbo.MBMTracking procedure:
#   sql/main/171_tracking_cases.sql                     genisis.Tracking_CaseText (fixed SELECT / GROUP BY text of each case)
#   src/Genisis.Api/Tracking/TrackingCaseKeys.g.cs      GROUP BY output columns per case (used to match supplementary rows)
# Each MBMTracking case is "<fixed SELECT ... FROM view WHERE ...>" + filter + "<fixed GROUP BY / ORDER BY>". genisis.Tracking_Run
# (sql/main/170_tracking.sql) adds the filter with typed parameters. Run after MBMTracking changes:
#   powershell -File tools/Generate-TrackingCases.ps1 [-Server .] [-Database HISDB]
param([string]$Server = '.', [string]$Database = 'HISDB')

$ErrorActionPreference = 'Stop'
$tmp = New-TemporaryFile
sqlcmd -S $Server -E -d $Database -y 0 -Q "SET NOCOUNT ON; SELECT OBJECT_DEFINITION(OBJECT_ID('dbo.MBMTracking'))" -o $tmp.FullName
$source = (Get-Content $tmp.FullName | Where-Object { $_ -notmatch '^\s*--' }) -join "`n"
Remove-Item $tmp

function Unquote([string]$literal) { $literal.Replace("''", "'") }
# MBMTracking was created with QUOTED_IDENTIFIER OFF, so "I" is a string there; genisis procedures use ON, where it must be 'I'.
function FixQuotes([string]$sql) { [regex]::Replace($sql, '"([^"\r\n]*)"', { param($m) "'" + $m.Groups[1].Value + "'" }) }
function OneLine([string]$s) { ($s -replace '\s+', ' ').Trim() }
function SqlLiteral([string]$s) { "N'" + (OneLine $s).Replace("'", "''") + "'" }

$blocks = [regex]::Split($source, "(?im)^\s*if\s+@strAppendCase\s*=\s*'?(\d+)'?\s*$")
$sqlCases = @(); $keyEntries = @()
for ($i = 1; $i -lt $blocks.Count; $i += 2) {
    $n = [int]$blocks[$i]; $body = $blocks[$i + 1]
    $literal = { param($name) $m = [regex]::Match($body, "set\s+@$name\d*\s*=\s*N?'((?:[^']|'')*)'", 'IgnoreCase'); if ($m.Success) { Unquote $m.Groups[1].Value } else { '' } }
    $prefix = FixQuotes (& $literal 'l_sqlstr')
    $groupBy = FixQuotes (& $literal 'l_sqlgroupby')
    $pivot = & $literal 'l_sqlpivot'
    $suffix = ($groupBy + ' ' + $pivot).Trim()

    $keys = @()
    $gb = [regex]::Match($groupBy, '(?is)GROUP\s+BY\s+(.*?)(\s+ORDER\s+BY.*)?$')
    if ($gb.Success -and $pivot -eq '') {
        foreach ($expr in ($gb.Groups[1].Value -split ',(?![^(]*\))')) {
            $e = $expr.Trim()
            $alias = [regex]::Match($prefix, [regex]::Escape($e) + '\s+AS\s+(\w+)', 'IgnoreCase')
            $keys += if ($alias.Success) { $alias.Groups[1].Value } elseif ($e -match '^[\w\.]+$') { $e.Split('.')[-1] } else { $null }
        }
        if ($keys -contains $null) { $keys = @() }
    }
    $sqlCases += "    WHEN $n THEN $(SqlLiteral $prefix)"
    $suffixCases += , "    WHEN $n THEN $(SqlLiteral $suffix)"
    $keyEntries += "        [$n] = [$(($keys | ForEach-Object { '"' + $_ + '"' }) -join ', ')],"
}

$sql = @"
-- GENERATED by tools/Generate-TrackingCases.ps1 from dbo.MBMTracking. Do not edit by hand; rerun the script instead.
-- Fixed query text of each MBMTracking case: prefix (SELECT ... FROM view WHERE ...) and suffix (GROUP BY / ORDER BY).
CREATE OR ALTER PROCEDURE genisis.Tracking_CaseText
    @case int, @prefix nvarchar(max) OUTPUT, @suffix nvarchar(max) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET @prefix = CASE @case
$($sqlCases -join "`n")
    END;
    SET @suffix = CASE @case
$($suffixCases -join "`n")
    END;
END
GO
"@
$keysFile = @"
// <auto-generated>
// Generated by tools/Generate-TrackingCases.ps1 from dbo.MBMTracking. Do not edit by hand; rerun the script instead.
// </auto-generated>
namespace Genisis.Api.Tracking;

/// <summary>Output columns of each MBMTracking case's GROUP BY (empty for member listings).</summary>
public static class TrackingCaseKeys
{
    public static readonly IReadOnlyDictionary<int, string[]> All = new Dictionary<int, string[]>
    {
$($keyEntries -join "`n")
    };
}
"@
$root = Join-Path $PSScriptRoot '..'
Set-Content -Path (Join-Path $root 'sql\main\171_tracking_cases.sql') -Value $sql -Encoding utf8
Set-Content -Path (Join-Path $root 'src\Genisis.Api\Tracking\TrackingCaseKeys.g.cs') -Value $keysFile -Encoding utf8
Write-Host "Wrote $($sqlCases.Count) cases."
